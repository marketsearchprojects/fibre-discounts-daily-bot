import assert from 'node:assert/strict';
import { calculate, comparisonCsv } from './calculator.mjs';
const a = { months: 24, initialMonths: 24, firstPrice: 28, laterPrice: 28, extras: 3, upfront: 0, switching: 0, reward: 50, reimbursement: 0 };
const b = { ...a, firstPrice: 30, laterPrice: 30, extras: 0, reward: 0 };
assert.equal(calculate(a).gross, 744);
assert.equal(calculate(a).total, 744);
assert.equal(calculate(a, true).total, 694);
assert.equal(calculate(a, true).monthly, 28.92);
assert.equal(calculate(b).total, 720);
assert.equal(calculate({ ...a, initialMonths: 12, firstPrice: 20, laterPrice: 30, extras: 0 }).gross, 600);
assert.equal(calculate({ ...a, initialMonths: 0, laterPrice: 30, extras: 0 }).gross, 720);
assert.equal(calculate({ ...a, switching: 100, reimbursement: 100 }, true).total, 694);
assert.equal(calculate({ ...a, months: 3, initialMonths: 3, firstPrice: 0.1, extras: 0 }).gross, 0.3);
for (const patch of [{ months: 0 }, { months: 121 }, { months: 2.5 }, { firstPrice: -1 }, { firstPrice: Infinity }, { reward: NaN }, { extras: '' }, { initialMonths: 25 }, { firstPrice: 1.234 }, { months: null }]) assert.throws(() => calculate({ ...a, ...patch }));
const csv = comparisonCsv(calculate(a), calculate(b));
assert.equal(csv.trim().split('\r\n').length, 3);
assert.ok(csv.includes('conditionalNet'));
assert.ok(csv.includes('false,744,31'));
console.log('22 calculator and CSV assertions passed.');
